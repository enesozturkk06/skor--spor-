#!/usr/bin/env node
/**
 * Builds the app's font assets into assets/fonts/ (run: npm run fonts:build).
 *
 * 1. Text fonts (Inter, Barlow Condensed — SIL OFL 1.1, no Reserved Font Name):
 *    only the 8 weights the app uses, subset to Latin + Latin Extended-A
 *    (full Turkish: çğıİöşü ÇĞÖŞÜ) and common punctuation/currency (₺ €).
 * 2. Icon font: only the glyphs listed in src/components/ui/icon-names.ts,
 *    taken from MaterialCommunityIcons (Pictogrammers MDI).
 *
 * 3. Web: the same subsets as content-hashed WOFF2 files in public/fonts/, the
 *    @font-face/preload block in public/index.html and assets/fonts/web-fonts.json.
 *
 * Output is committed; e2e/unit/fonts.spec.ts checks it is complete and current.
 */
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

import subsetFont from 'subset-font';

const require = createRequire(import.meta.url);
const OUT = 'assets/fonts';
mkdirSync(OUT, { recursive: true });

/* ----------------------------- text fonts ----------------------------- */

export const TEXT_RANGES = [
  [0x20, 0x7e], // Basic Latin
  [0xa0, 0xff], // Latin-1 (ç ö ü · × ² …)
  [0x100, 0x17f], // Latin Extended-A (ğ ı İ ş …)
  [0x2010, 0x2027], // dashes, quotes, bullet, ellipsis
  [0x2030, 0x2030],
  [0x2032, 0x2033],
  [0x2039, 0x203a],
  [0x20ac, 0x20ac], // €
  [0x20ba, 0x20ba], // ₺
  [0x2122, 0x2122],
  [0x2190, 0x2193], // arrows
  [0x2212, 0x2212], // minus
];
const textChars = TEXT_RANGES.flatMap(([a, b]) => Array.from({ length: b - a + 1 }, (_, i) => String.fromCodePoint(a + i))).join('');

const TEXT_FONTS = [
  ['BarlowCondensed_600SemiBold', '@expo-google-fonts/barlow-condensed', '600SemiBold'],
  ['BarlowCondensed_700Bold', '@expo-google-fonts/barlow-condensed', '700Bold'],
  ['BarlowCondensed_800ExtraBold', '@expo-google-fonts/barlow-condensed', '800ExtraBold'],
  ['BarlowCondensed_800ExtraBold_Italic', '@expo-google-fonts/barlow-condensed', '800ExtraBold_Italic'],
  ['Inter_400Regular', '@expo-google-fonts/inter', '400Regular'],
  ['Inter_500Medium', '@expo-google-fonts/inter', '500Medium'],
  ['Inter_600SemiBold', '@expo-google-fonts/inter', '600SemiBold'],
  ['Inter_700Bold', '@expo-google-fonts/inter', '700Bold'],
];

let before = 0;
let after = 0;
for (const [name, pkg, weight] of TEXT_FONTS) {
  const pkgDir = dirname(require.resolve(`${pkg}/package.json`));
  const src = readFileSync(join(pkgDir, weight, `${name}.ttf`));
  const out = await subsetFont(src, textChars, { targetFormat: 'truetype' });
  writeFileSync(join(OUT, `${name}.ttf`), out);
  before += src.length;
  after += out.length;
  console.log(`  ${name}: ${(src.length / 1024).toFixed(0)} KB -> ${(out.length / 1024).toFixed(0)} KB`);
}
for (const [pkg, file] of [
  ['@expo-google-fonts/inter', 'OFL-Inter.txt'],
  ['@expo-google-fonts/barlow-condensed', 'OFL-BarlowCondensed.txt'],
]) {
  copyFileSync(join(dirname(require.resolve(`${pkg}/package.json`)), 'LICENSE_FONT'), join(OUT, file));
}

/* ------------------------------ icon font ----------------------------- */

const VI = dirname(require.resolve('@expo/vector-icons/package.json'));
const VENDOR = join(VI, 'build/vendor/react-native-vector-icons');
const fullMap = JSON.parse(readFileSync(join(VENDOR, 'glyphmaps/MaterialCommunityIcons.json'), 'utf8'));

const registry = readFileSync('src/components/ui/icon-names.ts', 'utf8');
const listBody = /ICON_NAMES\s*=\s*\[([\s\S]*?)\]\s*as const/.exec(registry)?.[1];
if (!listBody) throw new Error('ICON_NAMES not found in icon-names.ts');
const names = [...listBody.matchAll(/'([a-z0-9-]+)'/g)].map((m) => m[1]);

const missing = names.filter((n) => !(n in fullMap));
if (missing.length) throw new Error(`Not MaterialCommunityIcons names: ${missing.join(', ')}`);
if (new Set(names).size !== names.length) throw new Error('Duplicate icon names in icon-names.ts');

const glyphMap = Object.fromEntries([...names].sort().map((n) => [n, fullMap[n]]));
const iconSrc = readFileSync(join(VENDOR, 'Fonts/MaterialCommunityIcons.ttf'));
const iconOut = await subsetFont(iconSrc, Object.values(glyphMap).map((cp) => String.fromCodePoint(cp)).join(''), { targetFormat: 'truetype' });
writeFileSync(join(OUT, 'skor-icons.ttf'), iconOut);
writeFileSync(join(OUT, 'skor-icons.json'), `${JSON.stringify(glyphMap, null, 2)}\n`);
before += iconSrc.length;
after += iconOut.length;
console.log(`  skor-icons (${names.length} glyphs): ${(iconSrc.length / 1024).toFixed(0)} KB -> ${(iconOut.length / 1024).toFixed(1)} KB`);

writeFileSync(
  join(OUT, 'LICENSES.md'),
  `# Font licenses

Generated by \`npm run fonts:build\` (scripts/build-fonts.mjs). Subsetting only removes glyphs;
no glyph outlines were changed.

- **Inter** — SIL Open Font License 1.1, see OFL-Inter.txt. Copyright 2020 The Inter Project Authors.
- **Barlow Condensed** — SIL Open Font License 1.1, see OFL-BarlowCondensed.txt. Copyright 2017 The Barlow Project Authors.
- **skor-icons.ttf** — subset of Material Design Icons (MaterialCommunityIcons) by Pictogrammers,
  distributed with @expo/vector-icons (MIT). MDI is licensed under Apache License 2.0 / SIL OFL 1.1:
  https://github.com/Templarian/MaterialDesign/blob/master/LICENSE
`,
);

console.log(`total: ${(before / 1024).toFixed(0)} KB -> ${(after / 1024).toFixed(0)} KB`);

/* --------------------------- web (WOFF2) fonts --------------------------- */
/*
 * The web build does not wait for fonts: public/index.html declares them with
 * @font-face (WOFF2, content-hashed names → cacheable forever) and preloads the
 * few the first screens need; the rest load when used or when the browser is idle.
 * The icon font uses font-display: block so icons never flash as boxes.
 */
const WEB_OUT = 'public/fonts';
const WEB_PRELOAD = new Set(['BarlowCondensed_800ExtraBold_Italic', 'Inter_400Regular', 'Inter_600SemiBold', 'skor-icons']);
mkdirSync(WEB_OUT, { recursive: true });
for (const f of readdirSync(WEB_OUT)) if (f.endsWith('.woff2')) unlinkSync(join(WEB_OUT, f));

const webFonts = {};
const writeWoff2 = (family, data) => {
  const file = `${family}.${createHash('sha256').update(data).digest('hex').slice(0, 10)}.woff2`;
  writeFileSync(join(WEB_OUT, file), data);
  webFonts[family] = `/fonts/${file}`;
  console.log(`  web ${file}: ${(data.length / 1024).toFixed(1)} KB`);
};
for (const [name, pkg, weight] of TEXT_FONTS) {
  const pkgDir = dirname(require.resolve(`${pkg}/package.json`));
  writeWoff2(name, await subsetFont(readFileSync(join(pkgDir, weight, `${name}.ttf`)), textChars, { targetFormat: 'woff2' }));
}
writeWoff2('skor-icons', await subsetFont(iconSrc, Object.values(glyphMap).map((cp) => String.fromCodePoint(cp)).join(''), { targetFormat: 'woff2' }));

writeFileSync(join(OUT, 'web-fonts.json'), `${JSON.stringify(webFonts, null, 2)}\n`);

const families = Object.keys(webFonts);
const block = [
  '<!-- skor-fonts:start -->',
  ...families.filter((f) => WEB_PRELOAD.has(f)).map((f) => `    <link rel="preload" href="${webFonts[f]}" as="font" type="font/woff2" crossorigin />`),
  '    <style id="skor-fonts">',
  ...families.map(
    (f) => `      @font-face { font-family: ${f}; src: url(${webFonts[f]}) format('woff2'); font-display: ${f === 'skor-icons' ? 'block' : 'swap'}; }`,
  ),
  '    </style>',
  '    <!-- skor-fonts:end -->',
].join('\n');
const TEMPLATE = 'public/index.html';
const html = readFileSync(TEMPLATE, 'utf8');
const marked = /<!-- skor-fonts:start -->[\s\S]*?<!-- skor-fonts:end -->/;
if (!marked.test(html)) throw new Error(`${TEMPLATE}: skor-fonts markers not found`);
writeFileSync(TEMPLATE, html.replace(marked, block));
console.log(`web fonts: ${families.length} files, ${WEB_PRELOAD.size} preloaded → ${TEMPLATE}`);
